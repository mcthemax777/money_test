-- 한 주를 어느 요일에서 끊는가.
--
-- 달력의 첫 칸과 거래 목록의 주 묶음이 함께 보는 값이다. 사람마다 다르게 세므로
-- 프로젝트가 아니라 계정에 둔다 -- 한 가계부를 함께 쓰는 두 사람이 서로 다른
-- 요일에서 주를 끊어도 원장은 달라지지 않는다.
--
-- 번호는 Date.getDay()와 같다 (0=일 … 6=토). 지금까지 모든 화면이 일요일에서
-- 끊었으므로 기본값은 0이고, 고치지 않은 계정은 보던 그대로 본다.
ALTER TABLE "User" ADD COLUMN "weekStart" INTEGER NOT NULL DEFAULT 0;
