/**
 * 한 프로젝트의 원장 쓰기를 줄 세우는 자문 잠금.
 *
 * **읽고-고쳐-쓰는 경로는 첫 문장에서 이것을 부른다.** 그러지 않으면 조건을 확인한
 * 값과 실제로 쓰는 값이 다를 수 있다. PostgreSQL 의 기본 격리 수준(READ COMMITTED)
 * 에서는 문장마다 새 스냅숏을 잡고 읽기는 아무 잠금도 걸지 않기 때문이다.
 *
 * 두 갈래에서 쓴다.
 *
 *   1. **전표 쓰기** (`LedgerService`). 옛 다리를 읽어 잔액에서 되돌린 뒤 새 다리를
 *      적용하는데, 그 사이 다른 요청이 같은 전표를 갈아 치우면 같은 금액을 두 번
 *      되돌려 통장 잔액만 조용히 어긋난다.
 *   2. **숨기기의 선행조건** (통장·카드·구성원·분류). "잔액이 0인가", "딸린 카드가
 *      없는가", "이 분류를 쓰는 거래가 없는가"를 확인한 다음 숨기는데, 확인과 쓰기
 *      사이에 그 조건을 깨는 요청이 끼어들 수 있다. 잔액이 남은 통장이 목록에서
 *      사라지면 총자산과 목록이 어긋난다.
 *
 * **왜 행 잠금이 아닌가.** 도장 트리거(`sync_next_version`)가 쓰기마다 프로젝트 행을
 * UPDATE 하므로 보통의 쓰기는 "제 행 -> 프로젝트 행" 순서로 잠근다. 여기서 프로젝트
 * 행을 먼저 잡으면 그 순서가 뒤집혀 교착이 난다. 자문 잠금은 이 경로들만 잡는 별도의
 * 이름이라 그 고리가 생기지 않는다 -- 이 잠금을 기다리는 트랜잭션은 아직 아무 행도
 * 잡고 있지 않기 때문이다. 그래서 **반드시 트랜잭션의 첫 문장이어야 한다.**
 *
 * 처리량은 사실상 그대로다. 위 트리거가 이미 프로젝트 단위로 쓰기를 직렬화하고 있어,
 * 잠그는 시점이 첫 쓰기에서 트랜잭션 머리로 앞당겨질 뿐이다.
 *
 * 트랜잭션이 끝나면 커밋이든 롤백이든 자동으로 풀린다. 같은 트랜잭션에서 두 번 불러도
 * 안전하다 -- 겹쳐 잡히고 함께 풀린다.
 */
import type { Prisma } from '@prisma/client';

/** 자문 잠금을 걸 수 있는 최소한의 모양. 트랜잭션 클라이언트가 이것을 만족한다. */
type LockableTx = Pick<Prisma.TransactionClient, '$executeRaw'>;

export async function lockLedgerWrites(tx: LockableTx, projectId: string): Promise<void> {
  // $queryRaw 는 void 반환을 역직렬화하지 못한다. 결과가 필요 없으므로 $executeRaw 다.
  await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtext(${`ledger-write:${projectId}`}))`;
}
